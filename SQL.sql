-- ################################################
-- OPTION A: Simulated Hierarchy (Run this right now)
-- Creates fake parent-child relationships by splitting category names.
-- E.g., "bed_bath_table" -> Parent: "home_furnishing"
-- ################################################

WITH 
-- Get the distinct categories from Olist
flat_categories AS (
    SELECT DISTINCT 
        p.product_category_name,
        COALESCE(t.product_category_name_english, p.product_category_name) AS category_english
    FROM products p
    LEFT JOIN product_category_name_translation t 
        ON p.product_category_name = t.product_category_name
    WHERE p.product_category_name IS NOT NULL
),

-- Manually create a synthetic parent-child mapping using CASE logic
-- (This mimics what a real parent_id column would look like)
category_hierarchy AS (
    SELECT 
        category_english AS child_category,
        CASE 
            WHEN category_english LIKE '%bed%' OR category_english LIKE '%bath%' OR category_english LIKE '%table%' 
                THEN 'home_furnishing'
            WHEN category_english LIKE '%computer%' OR category_english LIKE '%electronics%' OR category_english LIKE '%audio%' 
                THEN 'electronics_tech'
            WHEN category_english LIKE '%fashion%' OR category_english LIKE '%clothing%' OR category_english LIKE '%shoes%' 
                THEN 'apparel'
            WHEN category_english LIKE '%food%' OR category_english LIKE '%drink%' 
                THEN 'groceries'
            ELSE 'general_merchandise'
        END AS parent_category
    FROM flat_categories
),

-- THE RECURSIVE CTE (This is the gold-standard interview code)
recursive_tree AS (
    -- Anchor Member: Select all parent nodes (top level)
    SELECT 
        parent_category AS category_name,
        parent_category AS root_parent,
        0 AS level,
        CAST(parent_category AS VARCHAR(500)) AS path
    FROM category_hierarchy
    GROUP BY parent_category
    
    UNION ALL
    
    -- Recursive Member: Traverse down to children
    SELECT 
        h.child_category,
        r.root_parent,
        r.level + 1,
        CAST(CONCAT(r.path, ' -> ', h.child_category) AS VARCHAR(500))
    FROM category_hierarchy h
    INNER JOIN recursive_tree r ON h.parent_category = r.category_name
    WHERE r.level < 5 -- Safety limit to avoid infinite loops
)

-- Final Output: Flattened hierarchy with breadcrumb trail
SELECT 
    root_parent AS top_level_category,
    category_name AS sub_category,
    level AS depth_level,
    path AS category_breadcrumb
FROM recursive_tree
ORDER BY root_parent, level, category_name;


