WITH top_customers AS (
    SELECT 
        c.customer_unique_id,
        SUM(oi.price + oi.freight_value) AS total_spent
    FROM orders o
    JOIN customers c ON o.customer_id = c.customer_id
    JOIN order_items oi ON o.order_id = oi.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY c.customer_unique_id
    ORDER BY total_spent DESC
    LIMIT 100 -- Get the top 100 customers for analysis
),
top_customer_categories AS (
    SELECT 
        tc.customer_unique_id,
        COALESCE(pt.product_category_name_english, p.product_category_name) AS category,
        COUNT(oi.product_id) AS items_purchased
    FROM top_customers tc
    JOIN orders o ON o.customer_id = tc.customer_unique_id -- Note: Olist uses customer_id, not unique_id, in orders table. Adjust join accordingly.
    -- FIX: Actually, 'orders' table uses 'customer_id'. 'customers' table maps 'customer_id' to 'customer_unique_id'.
    -- Let's correct the join:
    -- Proper join: top_customers -> customers (to get customer_id) -> orders -> order_items -> products
    -- To keep it simple and error-proof for your schema, I'll rewrite the join cleanly:
)

-- Due to Olist's specific foreign keys, run this adjusted version instead of the above block:
SELECT 
    tc.customer_unique_id,
    tc.total_spent,
    COALESCE(trans.product_category_name_english, prod.product_category_name) AS preferred_category,
    COUNT(oi.product_id) AS purchase_frequency
FROM top_customers tc
JOIN customers c ON tc.customer_unique_id = c.customer_unique_id
JOIN orders o ON c.customer_id = o.customer_id
JOIN order_items oi ON o.order_id = oi.order_id
JOIN products prod ON oi.product_id = prod.product_id
LEFT JOIN product_category_name_translation trans 
    ON prod.product_category_name = trans.product_category_name
WHERE o.order_status = 'delivered'
GROUP BY tc.customer_unique_id, tc.total_spent, preferred_category
ORDER BY tc.total_spent DESC, purchase_frequency DESC;
