-- ################################################
-- SECTION 2: Customer Lifetime Value (CLV) Model
-- ################################################

WITH 
-- Step 2.1: Calculate raw revenue per customer
customer_revenue AS (
    SELECT 
        c.customer_unique_id,
        -- Total money spent (items + freight)
        SUM(oi.price + oi.freight_value) AS total_revenue,
        COUNT(DISTINCT o.order_id) AS total_orders,
        MIN(o.order_purchase_timestamp) AS first_purchase_date,
        MAX(o.order_purchase_timestamp) AS last_purchase_date,
        -- Calculate average order value (AOV)
        AVG(oi.price + oi.freight_value) AS avg_order_value
    FROM orders o
    JOIN customers c ON o.customer_id = c.customer_id
    JOIN order_items oi ON o.order_id = oi.order_id
    WHERE o.order_status = 'delivered' -- Exclude cancelled/fraudulent orders
    GROUP BY c.customer_unique_id
),

-- Step 2.2: Apply Window Functions to rank and segment customers
clv_ranking AS (
    SELECT 
        *,
        -- Total revenue generated by ALL customers (for percentage share)
        SUM(total_revenue) OVER() AS grand_total_revenue,
        
        -- Calculate the running cumulative revenue (Pareto curve)
        ROUND(
            100.0 * SUM(total_revenue) OVER (ORDER BY total_revenue DESC) 
            / SUM(total_revenue) OVER(), 2
        ) AS cumulative_revenue_percent,

        -- Percent Rank (1.0 = highest spender)
        ROUND(PERCENT_RANK() OVER (ORDER BY total_revenue DESC) * 100, 2) AS percentile_rank,

        -- NTILE: Split customers into 10 deciles (1 = Top 10%)
        NTILE(10) OVER (ORDER BY total_revenue DESC) AS revenue_decile,

        -- LAG: Show the revenue difference from the previous customer tier
        total_revenue - LAG(total_revenue, 1) OVER (ORDER BY total_revenue DESC) AS revenue_gap_from_previous
    FROM customer_revenue
)

-- Step 2.3: Final Output - Filtering for the Top 10% (Decile 1)
SELECT 
    customer_unique_id,
    total_revenue,
    total_orders,
    avg_order_value,
    first_purchase_date,
    last_purchase_date,
    revenue_decile,
    percentile_rank,
    ROUND(100.0 * total_revenue / grand_total_revenue, 2) AS revenue_share_percent,
    cumulative_revenue_percent
FROM clv_ranking
WHERE revenue_decile = 1  -- <<< CHANGE THIS to 2,3,4 to explore other tiers
ORDER BY total_revenue DESC;

